// @ts-check
import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";
import starlightLinksValidator from "starlight-links-validator";
import starlightLlmsTxt from "starlight-llms-txt";

// Starlight 0.42 on Astro 7. Set `site` to the real URL: sitemap, canonical links and llms.txt need it.
export default defineConfig({
  site: "https://docs.example.com",
  integrations: [
    starlight({
      title: "Tidewater docs",
      // The links validator fails the build on a broken internal link or #fragment.
      // llms.txt gives agents a plain-text index of the docs at /llms.txt.
      plugins: [starlightLinksValidator(), starlightLlmsTxt()],
      // Since Starlight 0.39 an autogenerated group is a group whose items hold the autogenerate config.
      sidebar: [
        { label: "Guides", items: [{ autogenerate: { directory: "guides" } }] },
        { label: "Reference", items: [{ autogenerate: { directory: "reference" } }] },
      ],
    }),
  ],
});
